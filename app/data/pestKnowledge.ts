function normalise(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim()
}

export function getPestKnowledge(label?: string | null) {
  const target = normalise(label || "")
  if (!target) return genericPest

  return pestKnowledge.find((entry) => {
    const candidates = [entry.id, entry.commonName, entry.scientificName, ...entry.aliases]
    return candidates.some((candidate) => normalise(candidate) === target)
  }) || genericPest
}

export function cropIsSupported(entry: PestKnowledge, crop?: string | null) {
  if (!crop || entry.crops.length === 0) return true
  const target = normalise(crop)
  return entry.crops.some((candidate) => normalise(candidate) === target)
}
