export function getTranslation(key: TranslationKey, language: Language): string {
  try {
    const selectedLanguage = translations[language] as Record<string, string>
    const englishLanguage = translations.en as Record<string, string>
    return selectedLanguage[key] || englishLanguage[key] || key
  } catch {
    return key
  }
}

export function t(key: TranslationKey, language: Language = "en"): string {
  return getTranslation(key, language)
}
